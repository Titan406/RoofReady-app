import { chromium } from 'playwright-core';
import fs from 'fs';
const [email, pw] = [process.env.E2E_EMAIL, process.env.E2E_PASSWORD];
const base = process.argv[2] || 'http://localhost:4173/';
const FX = '/workspace/roofready-app/test-fixtures/';
const S = '/tmp/rrui/shots/';
const b = await chromium.launch({ executablePath: '/usr/bin/google-chrome', args: ['--no-sandbox'] });
const ctx = await b.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2, isMobile: true, hasTouch: true });
const p = await ctx.newPage();
const errors = [];
p.on('pageerror', (e) => errors.push(String(e)));
p.on('console', (m) => m.type() === 'error' && errors.push(m.text()));
p.on('dialog', (d) => { console.log('DIALOG', d.message()); d.accept(); });
p.on('response', (r) => r.status() >= 400 && console.log('HTTP', r.status(), r.url().replace(/\?.*/, '')));
const log = (...a) => console.log(...a);
const hs = async (l) => log(l, 'scrollWidth', await p.evaluate(() => document.documentElement.scrollWidth));
await p.goto(base);
await p.fill('input[type=email]', email); await p.fill('input[type=password]', pw);
await p.click('button:has-text("Sign in")');
await p.waitForSelector('.jobcard');
// A: job with measurements, no estimate
await p.click('.jobcard:has-text("ZZ TEST A")');
await p.waitForSelector('text=Measurements & estimate');
log('job A card:', await p.innerText('.card:has(h2:has-text("Measurements & estimate"))'));
await p.screenshot({ path: S + 'A-job.png' });
await p.click('.card button:has-text(" estimate")');
await p.waitForSelector('.sumbar');
await p.waitForSelector('text=Rev 1');
log('A sumbar:', (await p.innerText('.sumbar')).replace(/\n/g, ' '));
log('A notice present:', !!(await p.$('.notice')));
await p.screenshot({ path: S + 'A-est-top.png' });
await p.mouse.wheel(0, 2500); await p.waitForTimeout(400);
log('A sumbar visible after scroll:', await p.$eval('.sumbar', (e) => { const r = e.getBoundingClientRect(); return r.top >= 0 && r.bottom < 300; }));
await p.screenshot({ path: S + 'A-est-scrolled.png' });
await hs('A estimate');
await p.click('button:has-text("‹ Job")');
await p.waitForSelector('text=Estimate price');
log('A job card after:', (await p.innerText('.card:has(h2:has-text("Measurements & estimate"))')).replace(/\n/g, ' | '));
await p.click('button:has-text("‹ Board")');
// B: no measurements
await p.click('.jobcard:has-text("ZZ TEST B")');
await p.waitForSelector('text=No measurements yet');
await p.click('.card button:has-text(" estimate")');
await p.waitForSelector('.notice');
log('B notice:', (await p.innerText('.notice')).replace(/\n/g, ' | '));
log('B sumbar:', (await p.innerText('.sumbar')).replace(/\n/g, ' '));
await p.screenshot({ path: S + 'B-est-empty.png' });
await p.click('.notice button:has-text("Upload report")');
await p.waitForSelector('text=Choose PDF');
await p.screenshot({ path: S + 'B-upload.png' });
// scanned
await p.setInputFiles('input[type=file]', FX + 'synthetic-scanned-no-text.pdf');
await p.waitForSelector('text=has no readable text');
log('scanned msg:', (await p.innerText('.error')).replace(/\n/g, ' '));
await p.screenshot({ path: S + 'B-scanned.png' });
// GAF
await p.setInputFiles('input[type=file]', FX + 'synthetic-gaf-quickmeasure.pdf');
await p.waitForSelector('text=Review numbers from the report');
log('found:', await p.$$eval('.revrow.found', (e) => e.length), 'missing:', await p.$$eval('.revrow.missing .revlabel b', (e) => e.map((x) => x.textContent).join(',')));
log('values:', await p.$$eval('.revrow input', (e) => e.map((x) => x.getAttribute('aria-label') + '=' + x.value).join(' ')));
log('source:', await p.inputValue('label:has-text("Measurement source") input'));
await hs('review');
await p.screenshot({ path: S + 'B-review.png', fullPage: true });
await p.click('button:has-text("Use these measurements")');
await p.waitForSelector('.sumbar');
await p.waitForSelector('text=Rev 1');
await p.waitForTimeout(500);
log('B after import sumbar:', (await p.innerText('.sumbar')).replace(/\n/g, ' '), '| notice:', !!(await p.$('.notice')));
log('B area field:', await p.inputValue('#m-area'), 'leakW:', await p.inputValue('#m-leakBarrierWidth'), 'src:', await p.inputValue('label:has-text("Measurement source") input'));
await p.screenshot({ path: S + 'B-est-after.png' });
// EagleView import on B again -> updates draft
await p.click('.card button:has-text("Upload PDF")');
await p.setInputFiles('input[type=file]', FX + 'synthetic-eagleview.pdf');
await p.waitForSelector('text=Review numbers from the report');
log('EV warnings:', await p.$$eval('.placeholder', (e) => e.map((x) => x.textContent).join(' || ')));
log('EV values:', await p.$$eval('.revrow input', (e) => e.map((x) => x.getAttribute('aria-label') + '=' + x.value).join(' ')));
await p.click('button:has-text("Use eaves + rakes = 340")');
log('ridgecap hint exists:', !!(await p.$('button:has-text("Use hips + ridges = 72")')));
await p.click('.revrow:has-text("Ridge cap") button:has-text("Use hips + ridges")');
await p.screenshot({ path: S + 'B-review-ev.png', fullPage: true });
await p.click('button:has-text("Use these measurements")');
await p.waitForSelector('.sumbar'); await p.waitForTimeout(800);
log('B after EV sumbar:', (await p.innerText('.sumbar')).replace(/\n/g, ' '), 'starter:', await p.inputValue('#m-starter'), 'ridgeCap:', await p.inputValue('#m-ridgeCap'), 'waste:', await p.inputValue('#m-waste'));
log('errors:', errors.length ? errors : 'none');
await b.close();
